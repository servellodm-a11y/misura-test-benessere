import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const html=fs.readFileSync('nextway-motore-ricerca.html','utf8');
const start=html.indexOf('function normalizeProspectIdentityPart(');
const end=html.indexOf('function buildProspectDedupeKey(',start);
assert.ok(start>=0&&end>start,'identity-key helpers must be present');
const sandbox={canonicalProspectUrl:value=>{try{const u=new URL(value);u.hash='';if(u.hostname.toLowerCase().startsWith('www.'))u.hostname=u.hostname.slice(4).toLowerCase();const normalized=u.toString();return normalized.endsWith('/')?normalized.slice(0,-1):normalized;}catch{return String(value||'').toLowerCase();}}};
vm.runInNewContext(html.slice(start,end)+';this.buildProspectIdentityKeys=buildProspectIdentityKeys;',sandbox);
const keys=sandbox.buildProspectIdentityKeys;
const profile={name:'Mario Rossi',profession:'Nutrizionista',organization:'Studio Salute',location:'Milano'};
const confirmed={individual:true};
const first=keys('https://www.example.it/profilo?utm_source=google',{},profile,confirmed,{});
const second=keys('https://directory.example/professionista',{}, {...profile,name:'Mario Róssi',organization:'Studio Salute'},confirmed,{});
assert.ok(first.some(k=>k.startsWith('person-role-org:')));
assert.ok(second.includes(first.find(k=>k.startsWith('person-role-org:'))),'normalized name, role and organization must identify cross-source duplicates');
const differentOrg=keys('https://other.example/mario',{}, {...profile,organization:'Centro Benessere'},confirmed,{});
assert.ok(!differentOrg.includes(first.find(k=>k.startsWith('person-role-org:'))),'different organization must not be auto-merged');
const nameOnly=keys('https://example.it/mario',{}, {name:'Mario Rossi',profession:'Non confermata',organization:'Non rilevata',location:'Non rilevata'},confirmed,{});
assert.equal(nameOnly.some(k=>k.startsWith('person-role-')),false,'name alone must never deduplicate people');
const unconfirmed=keys('https://example.it/mario',{},profile,{individual:false},{});
assert.equal(unconfirmed.some(k=>k.startsWith('person-role-')),false,'unconfirmed identity must not create a person key');
const genericEmail=keys('https://example.it/studio', {emails:['info@studio.it']}, {},{},{});
assert.equal(genericEmail.some(k=>k.startsWith('email:')),false,'generic organization inbox must not identify a person');
const personalEmail=keys('https://example.it/mario', {emails:['mario.rossi@example.it']}, {},{},{});
assert.ok(personalEmail.includes('email:mario.rossi@example.it'));
const phone=keys('https://example.it/mario', {phones:['+39 333 123 4567']}, {},{},{});
assert.ok(phone.includes('phone:393331234567'));
console.log('NEXTWAY conservative cross-source deduplication: 8 checks passed.');
